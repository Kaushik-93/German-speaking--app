export const ALL_PHRASES: Phrase[] = TOPICS.flatMap((t) =>
  t.phrases.map(([de, en, tip], i) => ({ id: `${t.key}-${i}`, de, en, tip, topic: t.key })),
);

export function topicOf(key: string): Topic | undefined {
  return TOPICS.find((t) => t.key === key);
}

